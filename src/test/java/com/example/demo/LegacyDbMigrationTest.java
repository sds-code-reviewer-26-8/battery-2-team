/**
 * G1: 공장 운영비 컬럼이 없던 이전 스키마의 H2 파일 DB 를 실제로 열어도(ddl-auto=update) 기동이 깨지지 않고,
 * 컬럼이 추가되며, 옛 공장은 기본 10억/일, 옛 주문은 운영비 0원(합계 재계산 없음)으로 보이는지 확인한다.
 */
@SpringBootTest
@AutoConfigureMockMvc
class LegacyDbMigrationTest {

	private static final long EOK = 100_000_000L;
	private static final String OLD_PLAN_JSON = """
			{"master":{"version":1,"shipCount":1,"shipDailyCostWon":100000000,
			"factories":[{"country":"CHINA","maxDaily":400,"stockLimit":4000,"unitCost":700}],
			"routes":[{"from":"KOREA","to":"CHINA","days":1}]},
			"orders":{"CHINA":400},"visits":{"CHINA":1},
			"plan":{"type":"COST","label":"운항비 최소","totalDays":2,"productionCost":280000000,
			"shippingCost":200000000,"totalCost":480000000,"ships":[],"stock":{},"production":{}}}
			""";

	private static final String URL;

	static {
		try {
			Path dir = Files.createTempDirectory("battery-legacy");
			dir.toFile().deleteOnExit();
			URL = "jdbc:h2:file:" + dir.resolve("battery").toAbsolutePath().toString().replace('\\', '/');
			createLegacyDatabase();
		} catch (IOException | SQLException e) {
			throw new IllegalStateException(e);
		}
	}

	/** 운영비 컬럼이 없는 이전 스키마와 옛 데이터를 JDBC 로 직접 만든다. */
	private static void createLegacyDatabase() throws SQLException {
		try (Connection c = DriverManager.getConnection(URL, "sa", ""); Statement s = c.createStatement()) {
			s.execute("create table factory (country varchar(255) not null primary key, max_daily integer not null,"
					+ " stock_limit integer not null, unit_cost bigint not null)");
			s.execute("insert into factory values ('CHINA',400,4000,700),('JAPAN',800,2000,900),"
					+ "('VIETNAM',200,10000,550),('INDONESIA',300,7000,450)");
			s.execute("create table route (id bigint generated by default as identity primary key,"
					+ " from_country varchar(255) not null, to_country varchar(255) not null, days integer not null,"
					+ " unique (from_country, to_country))");
			s.execute("insert into route (from_country,to_country,days) values ('KOREA','CHINA',1),('KOREA','JAPAN',2),"
					+ "('KOREA','VIETNAM',5),('KOREA','INDONESIA',7),('CHINA','JAPAN',2),('CHINA','VIETNAM',4),"
					+ "('CHINA','INDONESIA',6),('JAPAN','VIETNAM',5),('JAPAN','INDONESIA',7),('VIETNAM','INDONESIA',2)");
			s.execute("create table setting (id bigint not null primary key, ship_count integer not null,"
					+ " ship_daily_cost_won bigint not null, master_version bigint not null, lock_version bigint not null)");
			s.execute("insert into setting values (1,3," + EOK + ",5,0)");
			s.execute("create table orders (id bigint generated by default as identity primary key,"
					+ " confirmed_at timestamp(6) not null, created_by varchar(255) not null, totalk integer not null,"
					+ " route_type varchar(255), route_label varchar(255), total_days integer not null,"
					+ " production_cost bigint not null, shipping_cost bigint not null, total_cost bigint not null,"
					+ " status varchar(255) not null, memo varchar(1000), plan_json clob not null, version bigint not null)");
			try (var ps = c.prepareStatement("insert into orders (confirmed_at,created_by,totalk,route_type,route_label,"
					+ "total_days,production_cost,shipping_cost,total_cost,status,memo,plan_json,version)"
					+ " values (current_timestamp,'admin',400,'COST','운항비 최소',2,280000000,200000000,480000000,"
					+ "'CONFIRMED',null,?,0)")) {
				ps.setString(1, OLD_PLAN_JSON);
				ps.executeUpdate();
			}
		}
	}

	@DynamicPropertySource
	static void legacyDatabase(DynamicPropertyRegistry registry) {
		registry.add("spring.datasource.url", () -> URL);
		registry.add("spring.datasource.username", () -> "sa");
		registry.add("spring.datasource.password", () -> "");
		registry.add("spring.jpa.hibernate.ddl-auto", () -> "update");
	}

	@Autowired
	MockMvc mvc;
	@Autowired
	MasterService masters;
	@Autowired
	DataSource dataSource;

	private MockHttpSession login() throws Exception {
		MockHttpSession session = new MockHttpSession();
		mvc.perform(post("/api/login").contentType(MediaType.APPLICATION_JSON)
						.content("{\"username\":\"admin\",\"password\":\"admin\"}").session(session))
				.andExpect(status().isOk());
		return session;
	}

	private boolean hasColumn(String table, String column) throws SQLException {
		try (Connection c = dataSource.getConnection();
				ResultSet rs = c.getMetaData().getColumns(null, null, table.toUpperCase(), column.toUpperCase())) {
			return rs.next();
		}
	}

	@Test
	void legacyDatabaseGetsOperatingCostColumnsAndOldDataStaysIntact() throws Exception {
		// 컬럼 추가 성공 (컨텍스트가 떴다는 것 자체가 기동 성공)
		assertThat(hasColumn("factory", "operating_cost")).isTrue();
		assertThat(hasColumn("orders", "operating_cost")).isTrue();

		// 옛 공장은 기본 10억/일, 마스터 버전은 그대로
		Map<String, String> form = masters.masterForm();
		for (String country : new String[] {"CHINA", "JAPAN", "VIETNAM", "INDONESIA"}) {
			assertThat(form.get("operatingCost_" + country)).as(country).isEqualTo("10");
		}
		assertThat(masters.currentMaster().version()).isEqualTo(5);

		MockHttpSession s = login();

		// 옛 주문: 목록 운영비 0원, 합계 4.80억 그대로
		mvc.perform(get("/api/orders").session(s))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.total").value(1))
				.andExpect(jsonPath("$.orders[0].operatingCostEok").value("0.00"))
				.andExpect(jsonPath("$.orders[0].totalCostEok").value("4.80"));

		// 옛 주문 상세: 저장된 계획의 운영비 0, 합계 재계산 없음
		mvc.perform(get("/api/orders/1").session(s))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.plan.plan.operatingCost").value(0))
				.andExpect(jsonPath("$.plan.plan.totalCost").value(480_000_000));

		// 옛 DB 에서도 시뮬레이션이 운영비를 반영한다
		mvc.perform(post("/api/simulate").session(s).contentType(MediaType.APPLICATION_JSON)
						.content("{\"orders\":{\"CHINA\":400}}"))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.options.length()").value(3))
				.andExpect(jsonPath("$.options[0].operatingCost").value(Matchers.greaterThan(0)));

		// 마스터 저장: 운영비가 바뀌고 버전이 오른다
		form.put("operatingCost_CHINA", "12");
		masters.updateMaster(form);
		assertThat(masters.masterForm().get("operatingCost_CHINA")).isEqualTo("12");
		assertThat(masters.currentMaster().version()).isEqualTo(6);

		// 옛 주문은 마스터를 바꿔도 그대로
		mvc.perform(get("/api/orders").session(s))
				.andExpect(jsonPath("$.orders[0].operatingCostEok").value("0.00"))
				.andExpect(jsonPath("$.orders[0].totalCostEok").value("4.80"));
	}
}
